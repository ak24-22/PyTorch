# My notes

# Machine Learning (ML) and Deep Learning (DL) are very similar and used interchangebly in this YT Course.

# Machine Learning: A system that improves its performance on a task with more data or experience, enabling it to make predictions and decisions. It does this by turning any data types (audio files, images, text, videos, tables of numbers, etc...) into numbers and finding patterns in those numbers.

# Deep Learning: A system that goes through and analyses multiple layers of computation using neural networks to learn the patterns. This is a topic that is studied in Computer Science and is a subfield of Machine Learning which is a subfield of Artificial Intelligence.

# When to use ML/DL and what's it good for 
# --> Long or complex tasks, e.g., Driving a car properly
# --> Needs adapting, e.g., A smart thermostat that can change depending on the season
# -->  Massive datasets, e.g., Looks at 100 different dishes and identifies them

# When not to use ML/DL and what's it's not good for 
# --> Short or simple tasks, e.g., Turning lights on or off
# --> Needs explaining, e.g., Medical diagnosis  
# --> Flawless and 0 errors, e.g., Calculating chemotherapy dosages 
# --> Not enough data, e.g., predicting a rare disease

# ML vs DL (Traditionally, and in general)

# ML --> Structured data with tables, columns and rows, an example of a good algorithm for this is eXtreme Gradient Boost (XGBoost). this is used in Data Science cometitions and on the internet and Apps, another one is a Tree based algorithm, Other algorithms are Random Forest, Gradient Boosted Models, Naive Bayes, Nearest Neighbour, Support Vector Machine, and many more... These are known as Shallow Algorithms due to the rise of deep learning  

# DL --> Utructured data with different data format, a good algorithm for this is Neural Networks, so this would text/language formats and image formats and include audio formats Common Algorithms for deep learning are Fully Connected neural networks, Convolutional neural networks, Recurrent neural networks, Transformer and meny more...

# Course Focuses on: Neural Networks, Fully Connected neural networks and Convolutional neural networks

# Depending on users circumstances or situation, they could use ML for structured data or unstructured data and use DL for structured data or unstructured data
